/** Newest end (or ongoing) first; `num` follows display order. */
function workSortKey(item) {
  const src = String(item.period || `${item.year}.01`)
  const matches = [...src.matchAll(/(\d{4})\.(\d{2})/g)]
  const ym = (y, m) => Number(y) * 100 + Number(m)

  if (!matches.length) {
    return Number(item.year) * 100
  }

  const start = ym(matches[0][1], matches[0][2])
  const openEnded = /—\s*$/.test(src.trim()) && matches.length === 1
  const end =
    matches.length > 1
      ? ym(matches[matches.length - 1][1], matches[matches.length - 1][2])
      : openEnded
        ? 999912
        : start

  return end * 10000 + start
}

